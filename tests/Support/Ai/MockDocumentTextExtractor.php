<?php

namespace Tests\Support\Ai;

use App\Contracts\Documents\DocumentTextExtractor;
use App\Domains\Documents\Data\ExtractedTextResult;
use App\Models\PatientDocument;

class MockDocumentTextExtractor implements DocumentTextExtractor
{
    public function extract(PatientDocument $document): ExtractedTextResult
    {
        $warnings = [
            'Mock text extractor in use. Output is synthetic demonstration content.',
        ];

        $raw = '';

        if ($document->filesystem()->exists($document->path)) {
            $bytes = $document->filesystem()->get($document->path);

            // Only treat clearly textual payloads as readable source content.
            if (is_string($bytes) && preg_match('//u', $bytes) && ! str_contains($bytes, "\0")) {
                $candidate = trim($bytes);

                if ($candidate !== '' && strlen($candidate) < 20000) {
                    $raw = $candidate;
                }
            }
        }

        if ($raw === '') {
            $raw = implode("\n", [
                '[SYNTHETIC DEMO DOCUMENT]',
                'This content was generated by CareFlow mock AI for demonstration only.',
                'Original filename: '.$document->original_filename,
                'No real patient clinical content was inferred from this file.',
                'Document category hint: '.$document->category->label(),
                'Reported findings: not available in mock extraction.',
                'Uncertain sections: full source text could not be OCR-read by the mock provider.',
            ]);
            $warnings[] = 'Binary/unreadable source; synthetic placeholder text returned.';
        } else {
            $raw = "[SYNTHETIC DEMO WRAPPER]\n".$raw."\n[END SYNTHETIC DEMO WRAPPER]";
        }

        return new ExtractedTextResult(
            text: $raw,
            provider: 'mock',
            isSynthetic: true,
            warnings: $warnings,
        );
    }
}
