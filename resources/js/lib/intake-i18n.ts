export function intakeText(locale: string, key: string): string {
    const normalized = (
        ['en', 'tr', 'ar', 'ru', 'az'].includes(locale) ? locale : 'en'
    ) as IntakeLocale;

    return dictionary[normalized][key] ?? dictionary.en[key] ?? key;
}

export function isRtl(locale: string): boolean {
    return locale === 'ar';
}
